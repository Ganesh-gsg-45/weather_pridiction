@app.route("/api/trends", methods=["GET"])
def api_trends_data():
    """
    Return historical daily averages for a city over a day-of-year window.

    Query params:
      city      : str  — must match a city name in HIST_AVG (case-sensitive)
      doy_start : int  — start day-of-year (1-365), default = today
      doy_end   : int  — end day-of-year   (1-365), default = doy_start + 29
      metric    : str  — one of: tmax, tmin, precip, wind (default: tmax)

    Returns JSON:
      {
        "city": "Delhi",
        "metric": "tmax",
        "doy_start": 220,
        "doy_end": 249,
        "data": [
          {"doy": 220, "value": 33.5, "samples": 25},
          ...
        ]
      }
    """
    city   = request.args.get("city", "")
    metric = request.args.get("metric", "tmax")

    # Default window: today ± 0 → +29 days (30-day window)
    today_doy = datetime.now(UTC).timetuple().tm_yday
    try:
        doy_start = int(request.args.get("doy_start", today_doy))
        doy_end   = int(request.args.get("doy_end",   today_doy + 364))
    except ValueError:
        return jsonify({"error": "doy_start and doy_end must be integers"}), 400

    if metric not in ("tmax", "tmin", "precip", "wind"):
        return jsonify({"error": f"Invalid metric '{metric}'. Choose: tmax, tmin, precip, wind"}), 400

    if not city:
        return jsonify({"error": "city param required"}), 400

    matched_city = find_hist_city(city)
    if not matched_city:
        available = sorted(HIST_AVG.keys())
        return jsonify({
            "error": f"City '{city}' not in historical dataset.",
            "available_cities": available
        }), 404

    city_data = HIST_AVG[matched_city]
    city = matched_city

    # Collect doy range, wrapping around year end (e.g. 350 → 365 → 1 → 15)
    data = []
    total_days = doy_end - doy_start + 1
    for offset in range(max(total_days, 1)):
        doy = ((doy_start - 1 + offset) % 365) + 1   # 1-365, wraps
        entry = city_data.get(str(doy))
        if entry:
            data.append({
                "doy":     doy,
                "value":   entry[metric],
                "samples": entry["samples"],
            })

    return jsonify({
        "city":      city,
        "metric":    metric,
        "doy_start": doy_start,
        "doy_end":   doy_end,
        "data":      data,
    })


