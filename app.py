def get_country_flag(country_code: str) -> str:
    """Return unicode emoji flag from 2-letter ISO country code."""
    if not country_code or len(country_code) != 2:
        return "🌍"
    try:
        return "".join(chr(127397 + ord(c)) for c in country_code.upper())
    except Exception:
        return "🌍"


