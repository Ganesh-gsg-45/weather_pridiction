def owm_id_to_wmo_code(owm_id: int) -> int:

    if owm_id == 800:
        return 0    # Clear sky
    if owm_id == 801:
        return 1    # Mainly clear
    if owm_id == 802:
        return 2    # Partly cloudy
    if owm_id in (803, 804):
        return 3    # Overcast
    if 700 <= owm_id <= 799:
        # Atmosphere: mist(701), smoke(711), haze(721), dust(731,761),
        # fog(741), sand(751), ash(762), squall(771), tornado(781)
        return 45   # Fog / haze
    if 300 <= owm_id <= 321:
        # Drizzle: light(300,301), moderate(302,311), heavy(312,314,321)
        if owm_id in (300, 301, 310):
            return 51   # Light drizzle
        if owm_id in (302, 311, 313):
            return 53   # Moderate drizzle
        return 55       # Dense drizzle
    if 500 <= owm_id <= 531:
        # Rain
        if owm_id == 500:
            return 61   # Slight rain
        if owm_id == 501:
            return 63   # Moderate rain
        if owm_id in (502, 503, 504):
            return 65   # Heavy rain (dataset max)
        if owm_id in (511, 520):
            return 61   # Freezing / light shower → slight rain
        if owm_id in (521, 522, 531):
            return 63   # Shower rain
        return 61
    if 600 <= owm_id <= 622:
        # Snow — rare for India; map to light rain equivalent
        return 61
    if 200 <= owm_id <= 232:
        # Thunderstorm — cap at 65 (dataset max; WMO 95+ not in training data)
        return 65
    return 3  # fallback: overcast


def compute_moon_phase(dt: datetime = None) -> dict:
    """
    Compute moon phase using a standard lunar cycle formula.
    Returns phase_name, phase_icon, and illumination (0-1).
    No external API needed.
    """
    if dt is None:
        dt = datetime.now(UTC)

    # Known new moon reference: Jan 6, 2000
    known_new_moon = datetime(2000, 1, 6, 18, 14, tzinfo=UTC)
    lunar_cycle = 29.53058867  # days

    delta = dt - known_new_moon
    days_since = delta.total_seconds() / 86400.0
    phase_position = (days_since % lunar_cycle) / lunar_cycle  # 0.0 – 1.0

    # Illumination fraction (simple cosine model)
    illumination = (1 - math.cos(2 * math.pi * phase_position)) / 2

    # Phase name buckets
    if phase_position < 0.0625:
        name, icon = "New Moon", "🌑"
    elif phase_position < 0.1875:
        name, icon = "Waxing Crescent", "🌒"
    elif phase_position < 0.3125:
        name, icon = "First Quarter", "🌓"
    elif phase_position < 0.4375:
        name, icon = "Waxing Gibbous", "🌔"
    elif phase_position < 0.5625:
        name, icon = "Full Moon", "🌕"
    elif phase_position < 0.6875:
        name, icon = "Waning Gibbous", "🌖"
    elif phase_position < 0.8125:
        name, icon = "Last Quarter", "🌗"
    elif phase_position < 0.9375:
        name, icon = "Waning Crescent", "🌘"
    else:
        name, icon = "New Moon", "🌑"

    return {
        "name": name,
        "icon": icon,
        "illumination": round(illumination * 100),
        "position": round(phase_position * 100),
    }


